#!/usr/bin/env python3
"""Export the running API's Swagger document to docs/openapi.yaml.

The runtime document is authoritative. This emitter writes block-style YAML without third-party
dependencies, adds the course server URL and keeps every schema and response the API produces.

    python scripts/generate-openapi.py [http://localhost:5047] [docs/openapi.yaml]
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request

PLAIN_KEY = re.compile(r"^[A-Za-z0-9_./{}$-]+$")


def scalar(value):
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    return json.dumps(str(value), ensure_ascii=False)


def emit(value, indent, lines):
    pad = "  " * indent

    if isinstance(value, dict):
        if not value:
            lines.append(f"{pad}{{}}")
            return
        for key, child in value.items():
            key_text = str(key)
            key_out = key_text if PLAIN_KEY.match(key_text) else json.dumps(key_text, ensure_ascii=False)
            if isinstance(child, dict):
                if child:
                    lines.append(f"{pad}{key_out}:")
                    emit(child, indent + 1, lines)
                else:
                    lines.append(f"{pad}{key_out}: {{}}")
            elif isinstance(child, list):
                if child:
                    lines.append(f"{pad}{key_out}:")
                    emit(child, indent + 1, lines)
                else:
                    lines.append(f"{pad}{key_out}: []")
            elif isinstance(child, str) and "\n" in child:
                lines.append(f"{pad}{key_out}: |-")
                for line in child.splitlines():
                    lines.append("  " * (indent + 1) + line)
            else:
                lines.append(f"{pad}{key_out}: {scalar(child)}")
        return

    if isinstance(value, list):
        if not value:
            lines.append(f"{pad}[]")
            return
        for item in value:
            if isinstance(item, (dict, list)):
                lines.append(f"{pad}-")
                emit(item, indent + 1, lines)
            else:
                lines.append(f"{pad}- {scalar(item)}")
        return

    lines.append(f"{pad}{scalar(value)}")


def main() -> int:
    base = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:5047"
    target = sys.argv[2] if len(sys.argv) > 2 else "docs/openapi.yaml"

    with urllib.request.urlopen(f"{base.rstrip('/')}/swagger/v1/swagger.json", timeout=20) as response:
        document = json.load(response)

    document.setdefault("servers", [{"url": base.rstrip("/"), "description": "Local development"}])

    lines = ["# Generated by scripts/generate-openapi.py from the running API.", "# Do not edit by hand."]
    emit(document, 0, lines)

    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")

    paths = len(document.get("paths", {}))
    operations = sum(1 for path in document.get("paths", {}).values() for method in path if method in
                     {"get", "post", "put", "patch", "delete", "head", "options"})
    print(f"Wrote {target}: {paths} paths, {operations} operations, {len(document.get('components', {}).get('schemas', {}))} schemas")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
